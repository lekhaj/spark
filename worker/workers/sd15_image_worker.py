#!/usr/bin/env python3
"""
SD 1.5 Image Worker  (extends BaseWorker)
=========================================
Stage 1: SD1.5 + ControlNet → clean base structure (pose/silhouette)
Stage 2: SD1.5 img2img      → add clothing / textures / aura

ControlNet routing:
  bipedal / humanoid → lllyasviel/control_v11p_sd15_openpose  (COCO-18 T-pose)
  quadruped          → lllyasviel/control_v11p_sd15_openpose   (uses quad skeleton image)

Prompt strategy (CLIP ~75 token limit):
  Stage 1 — structure only: pose, proportions, plain outfit, white bg
  Stage 2 — detail pass: clothing, style, atmosphere, quality prefix
"""

